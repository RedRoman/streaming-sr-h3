@contextmanager
def differentiable_decoder_math():
    """Use upstream eager RoPE math where the inference kernel lacks autograd.

    This changes no official files or weights. The scoped training flag selects
    upstream differentiable linear math; the RoPE function is the installed
    package's own eager reference implementation. Forward parity is audited by
    decoder_gradient_smoke.py before RGB supervision uses this context.
    """
    import comfy.model_management
    import comfy.quant_ops
    from comfy_kitchen.backends.eager.rope import rms_rope_split_half
    previous_training=comfy.model_management.in_training
    previous_rope=comfy.quant_ops.ck.rms_rope_split_half
    try:
        comfy.model_management.in_training=True
        comfy.quant_ops.ck.rms_rope_split_half=rms_rope_split_half
        yield
    finally:
        comfy.model_management.in_training=previous_training
        comfy.quant_ops.ck.rms_rope_split_half=previous_rope


@dataclass(frozen=True)
class StreamBlock:
    start: int
    stop: int
    emit_start: int
    max_input_wait_frames: int


def stream_blocks(frames=39,length=22,overlap=5):
    if length%17!=5:raise ValueError('H3 block length must be 17k+5')
    if not 0<=overlap<length:raise ValueError('Invalid overlap')
    stride=length-overlap
    blocks=[]
    for start in range(0,frames-length+1,stride):
        blocks.append(StreamBlock(start,start+length,start if start==0 else start+overlap,length-1))
    if not blocks or blocks[-1].stop!=frames:
        raise ValueError('Frame count must end on the explicit block schedule')
    return blocks


def guide_payload(guides,block,seed=17):
    """Guides are (relative target frame, latent, last observed source frame).

    The returned payload contains independent, non-denoised condition rows.
    It deliberately does not replace the target AV latent or set denoise_mask.
    Each block may use all inputs up to stop-1: this is bounded waiting, not
    zero-lookahead streaming. Already emitted overlap frames are not re-emitted.
    """
    keyframes=[]
    for relative_index,latent,last_observed in guides:
        if last_observed>=block.stop:raise ValueError('Guide uses an unavailable future observation')
        if not 0<=relative_index<block.stop-block.start:raise ValueError('Guide anchor outside target block')
        if latent.ndim!=5 or latent.shape[:2]!=(1,24):raise ValueError('Expected H3 [1,24,T,H/16,W/16] guide')
        latent_t=latent.shape[2]
        if latent_t!=1 and (latent_t<2 or (latent_t-2)%5):raise ValueError('Guide temporal latent length must be 1 or 5k+2')
        guide_frames=1 if latent_t==1 else (latent_t-2)//5*17+5
        if relative_index+guide_frames>block.stop-block.start:raise ValueError('Guide clip extends beyond target block')
        if latent.shape[-1]%2 or latent.shape[-2]%2:raise ValueError('H3 video patch grid requires even latent spatial dimensions')
        keyframes.append({'resolved_frame_index':relative_index,'latent':latent})
    return {'keyframes':keyframes,'cond_video_latents':[x['latent'] for x in keyframes],'seed':seed}


def load_frozen_vae(path,device='cuda',dtype=torch.float16):
    """Load the unmodified upstream native VAE, not a surrogate autoencoder."""
    from safetensors.torch import load_file
    from comfy.ldm.minimax.vae import MiniMaxH3VideoVAE
    state=load_file(str(Path(path)),device='cpu')
    layers=sum(k.startswith('decoder.transformer_blocks.') and k.endswith('.scale1') for k in state)
    if not layers:raise ValueError('Checkpoint is not the expected native H3 VAE')
    old_default=torch.get_default_dtype()
    try:
        torch.set_default_dtype(dtype)
        with torch.device(device):model=MiniMaxH3VideoVAE(num_layers=layers)
    finally:torch.set_default_dtype(old_default)
    missing,unexpected=model.load_state_dict(state,strict=False)
    # These buffers can be regenerated by the official constructor.
    allowed={'latents_mean','latents_std'}
    if set(missing)-allowed or unexpected:raise RuntimeError({'missing':missing,'unexpected':unexpected})
    model.eval().requires_grad_(False)
    return model,{'layers':layers,'checkpoint':str(path),'dtype':str(dtype),'missing_buffers':missing}


def decoder_teacher(vae,anchor,p0,roi,epsilon=.1,output_frame=0):
    """Finite differences of the real H3 decoder in fixed P0 coordinates.

    P0 is fixed throughout basis learning. A trainable C may change freely:
    K(C)=K0 C remains the same first-order teacher. Report epsilon sensitivity
    and decoded LR residuals; this approximation is never an exact nullspace.
    """
    y,x=roi;tile=int((p0.shape[0]//(24*anchor.shape[2]))**.5)
    # Native temporal decode may stream its output to CPU even when its
    # computation and input latent live on CUDA. Normalize that boundary here.
    base=vae.decode(anchor)[:,:,output_frame].to(device=anchor.device,dtype=torch.float32)
    directions=[]
    for atom in p0.T:
        delta=torch.zeros_like(anchor)
        delta[:,:,:,y:y+tile,x:x+tile]=atom.reshape(1,24,anchor.shape[2],tile,tile).to(anchor)
        plus=vae.decode(anchor+epsilon*delta)[:,:,output_frame].to(device=anchor.device,dtype=torch.float32)
        minus=vae.decode(anchor-epsilon*delta)[:,:,output_frame].to(device=anchor.device,dtype=torch.float32)
        directions.append((plus-minus)/(2*epsilon))
    return base,torch.cat(directions,0)


def memory_clip_guide(vae,canonical_rgb,canonical_rectangle,packets,view_size=256,appearance=False):
    """Render canonical memory into ALREADY OBSERVED current views, then encode.

    This can replace the baseline's one LR-upsample guide clip, preserving guide
    token count and DiT calls. Unknown/occluded pixels are filled from current LR,
    so foreground occluders are not erased by the background identity memory.
    Oracle geometry/visibility is explicit in this controlled-camera interface.
    The caller must use guide_payload to enforce its block endpoint/wait budget.
    """
    from camera_operator import camera_footprint
    if len(packets)%17!=5:raise ValueError('Guide clip must have native 5/22/... frames')
    device=canonical_rgb.device;views=[];fractions=[]
    for packet in packets:
        observed=torch.as_tensor(packet.rgb.copy(),device=device).permute(2,0,1)[None].float()/255
        current=F.interpolate(observed,size=(view_size,view_size),mode='bicubic',align_corners=False,antialias=True).clamp(0,1)
        kwargs=dict(canonical_rectangle=canonical_rectangle,view_rectangle=packet.world_rectangle,view_size=(view_size,view_size),lr_size=(view_size,view_size),blur=0)
        rendered=camera_footprint(canonical_rgb,**kwargs)
        coverage=camera_footprint(torch.ones_like(canonical_rgb[:,:1]),**kwargs).clamp(0,1)
        visibility=torch.as_tensor(packet.visible_mask.copy(),device=device)[None,None].float()/255
        visibility=F.interpolate(visibility,size=(view_size,view_size),mode='nearest')
        weight=visibility*(coverage>.999)
        if appearance:
            # Instantaneous appearance is fitted from current real LR and never
            # written into the persistent canonical identity coefficients.
            down=F.interpolate(rendered,size=observed.shape[-2:],mode='bicubic',align_corners=False,antialias=True)
            valid=F.interpolate(weight,size=observed.shape[-2:],mode='nearest')[0,0]>.5
            channels=[]
            for channel in range(3):
                design=torch.stack([down[0,channel][valid],torch.ones_like(down[0,channel][valid])],1)
                if len(design)>6:
                    target=observed[0,channel][valid]
                    coefficient=torch.linalg.solve(design.T@design+torch.eye(2,device=device)*1e-4,design.T@target)
                    channels.append(rendered[:,channel:channel+1]*coefficient[0]+coefficient[1])
                else:channels.append(rendered[:,channel:channel+1])
            rendered=torch.cat(channels,1)
        views.append((weight*rendered+(1-weight)*current).clamp(0,1))
        fractions.append(float(weight.mean().detach()))
    clip=torch.stack(views,2)
    encoded=vae.encode((2*clip-1).half().clone())
    return encoded,{'source_indices':[p.index for p in packets],
                    'last_observed_index':max(p.index for p in packets),
                    'memory_pixel_fraction':fractions,'guide_clips':1,
                    'input_usage':'LR + oracle geometry/visibility only; canonical memory decoded from prior LR state'}
