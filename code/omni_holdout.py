"""Evaluate a trained omni estimator on operators it never saw, which is where the two conditioning
signals stop being interchangeable.

On the five operators both arms trained on, they are indistinguishable -- measured, not assumed: mtf minus
onehot is -0.030/-0.032/-0.072/-0.144/-0.014 dB at x2/x4/x8/deblur/denoise, i.e. mtf is slightly BEHIND
everywhere. That is the result this experiment needs. If a wider conditioning vector had won inside the
vocabulary, the gain would have been capacity and nothing here would be about expressiveness.

x6 is the separation. It was generated by the same pair pipeline but excluded from every training run, and
the probe says where it should land: band 0 reads 1.00/0.98/0.88 for x4/x6/x8 and band 1 reads
0.83/0.44/0.17, so x6 sits strictly between two operators the model did train on, in every band. An MTF
condition can therefore be evaluated at x6 by construction. A one-hot cannot be evaluated at x6 at all --
not scored badly, but undefined, since OPS has no slot for it.

That asymmetry, not a dB delta, is the claim. So the one-hot arm's refusal is recorded here as a result
with its own message rather than caught and turned into a zero.
"""
import argparse
import json
import sys
from pathlib import Path

import numpy as np
import torch

sys.path.insert(0, str(Path(__file__).resolve().parent))
ROOT = Path('/cache/zihaohe/streaming_sr0')
OUT = ROOT / 'results/omni'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ckpt', action='append', required=True, help='tag or path, repeatable')
    ap.add_argument('--ops', default='6', help='operators to evaluate')
    ap.add_argument('--val-limit', type=int, default=24)
    ap.add_argument('--device', default='npu:0')
    ap.add_argument('--out', default='omni_holdout.json')
    ap.add_argument('--mis-cond', default='',
                    help="evaluate the data of --ops while FEEDING the descriptor of these operators "
                         'instead. The control that decides what the x6 result means: if the model scores '
                         'the same on x6 data whether it is handed x6, x4 or x8 descriptors, then it is '
                         'simply operator-agnostic and the conditioning is doing no work, and the '
                         'interpolation claim is unsupported. The correct descriptor must win.')
    a = ap.parse_args()

    dev = torch.device(a.device)
    if a.device.startswith('npu'):
        import torch_npu  # noqa: F401
        from h3_comfy import patch_module_to, set_precision
        patch_module_to(); set_precision()
        _claim = torch.zeros(1 << 28, device=dev); del _claim
    from omni_stage1 import COND_DIM, DATA, Multi, OmniRange, evaluate

    ops = [int(x) if x.isdigit() else x for x in a.ops.split(',') if x]
    mis_ops = [int(x) if x.isdigit() else x for x in a.mis_cond.split(',') if x]
    rows = {}
    for spec in a.ckpt:
        p = Path(spec) if '/' in spec else OUT / f'{spec}.pt'
        tag = p.stem
        st = torch.load(p, map_location='cpu')
        cfg = dict(st['cfg'])
        cfg.pop('omni', None); cfg.pop('ops', None)
        mode = cfg.pop('cond', 'onehot')
        k = int(cfg.get('k', 1))
        cfg.setdefault('cdim', COND_DIM[mode])
        model = OmniRange(**cfg).eval()
        model.load_state_dict(st['state'])
        model = model.to(dev)
        rows[tag] = {'cond': mode, 'k': k, 'ops': {}}
        for op in ops:
            if not Path(DATA[op]).is_dir():
                rows[tag]['ops'][str(op)] = {'status': 'no pairs at %s' % DATA[op]}
                continue
            # The refusal is raised by cond(), which Multi() does not call -- evaluate() does. Wrapping
            # only the construction let the one-hot arm's SystemExit escape and take the whole run with
            # it (exit 1, no JSON written), losing the mtf numbers that had already been measured.
            try:
                d = Multi('val', [op], limit=a.val_limit, mode=mode, k=k)
                ev = evaluate(model, d, dev, use_sev=False)
            except SystemExit as e:
                rows[tag]['ops'][str(op)] = {'status': 'UNREPRESENTABLE', 'reason': str(e)}
                print(json.dumps({'ckpt': tag, 'cond': mode, 'op': str(op),
                                  'result': 'UNREPRESENTABLE'}), flush=True)
                continue
            v = ev[op]
            rows[tag]['ops'][str(op)] = {'status': 'ok', 'n': v['n'], 'base': v['base'],
                                         'psnr': v['psnr'], 'gain_dB': v['gain_dB']}
            print(json.dumps({'ckpt': tag, 'cond': mode, 'k': k, 'op': str(op), 'n': v['n'],
                              'base_dB': round(v['base'], 3), 'psnr_dB': round(v['psnr'], 3),
                              'gain_dB': round(v['gain_dB'], 3)}), flush=True)
            # Mis-conditioning control: same data, a descriptor belonging to a different operator.
            for mis in mis_ops:
                if mis == op:
                    continue
                d.mode, d.item[0]  # d is reused; only the conditioning vector changes
                saved = d.cond
                d.cond = (lambda sc, sv, us, _m=mis: Multi.cond(d, _m, sv, us))
                evm = evaluate(model, d, dev, use_sev=False)
                d.cond = saved
                vm = evm[op]
                rows[tag]['ops'][str(op)].setdefault('mis', {})[str(mis)] = {
                    'psnr': vm['psnr'], 'gain_dB': vm['gain_dB']}
                print(json.dumps({'ckpt': tag, 'op': str(op), 'fed_descriptor_of': str(mis),
                                  'psnr_dB': round(vm['psnr'], 3),
                                  'gain_dB': round(vm['gain_dB'], 3),
                                  'cost_of_wrong_descriptor_dB':
                                      round(vm['gain_dB'] - v['gain_dB'], 3)}), flush=True)
    (OUT / a.out).write_text(json.dumps(rows, indent=1))

    print()
    print('%-18s %-7s %-3s %-9s %10s %10s %10s' % ('checkpoint', 'cond', 'K', 'operator',
                                                   'base dB', 'psnr dB', 'gain dB'))
    for tag, r in rows.items():
        for op, v in r['ops'].items():
            if v['status'] == 'ok':
                print('%-18s %-7s %-3d %-9s %10.3f %10.3f %+10.3f'
                      % (tag, r['cond'], r['k'], op, v['base'], v['psnr'], v['gain_dB']))
            else:
                print('%-18s %-7s %-3d %-9s %s' % (tag, r['cond'], r['k'], op, v['status']))
    print()
    print('wrote', OUT / a.out)


if __name__ == '__main__':
    main()
